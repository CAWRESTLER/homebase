// Regenerates supabase/seed.sql from src/data/seed.ts:  npm run gen:seed-sql
import { writeFileSync } from 'node:fs';
import { SEED_AREAS, SEED_ROWS } from '../src/data/seed';

// Emit pure-ASCII SQL: non-ASCII chars become E'\uXXXX' escapes so pasting into any editor/encoding is safe.
const q = (s: string) => {
  const body = s.replace(/'/g, "''");
  if (/^[\x20-\x7e]*$/.test(body)) return `'${body}'`;
  return `E'${body.replace(/\\/g, '\\\\').replace(/[^\x20-\x7e]/g, (c) => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'))}'`;
};
const lines: string[] = [
  '-- Homebase seed data (generated by scripts/gen-seed-sql.ts - do not edit by hand). Pure ASCII on purpose.',
  `-- ${SEED_AREAS.length} areas, ${SEED_ROWS.length} tasks. Safe to re-run: it only inserts missing rows.`,
  'begin;',
  '',
  'insert into public.areas (name, sort_order) values',
  SEED_AREAS.map((a, i) => `  (${q(a.name)}, ${i})`).join(',\n'),
  'on conflict (name) do nothing;',
  '',
  'insert into public.tasks (title, area, priority, sort_order)',
  'select v.title, v.area, v.priority, v.sort_order from (values',
  SEED_ROWS.map((r) => `  (${q(r.title)}, ${q(r.area)}, ${q(r.priority)}, ${r.order})`).join(',\n'),
  ') as v(title, area, priority, sort_order)',
  'where not exists (select 1 from public.tasks t where t.title = v.title and t.area = v.area);',
  '',
  'commit;',
  '',
];
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), lines.join('\n'));
console.log(`Wrote supabase/seed.sql with ${SEED_ROWS.length} tasks`);
